#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Plot 5 narrow-bin bar charts plus 2 scatter charts from REAL Oganov C32 per-structure results.

Usage:
 python plot_C32_oganov_7figures.py 01_all_structures_to_C32_oganov.csv

Input generated by compare_five_groups_to_C32_oganov.py.
No data interpolation. Bars denote a percentage of ALL valid structures of that group,
not only structures with S >= 0.8. Similarity S = 1 - D (Oganov cosine distance).
"""
import argparse
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

plt.rcParams.update({
    'font.family': ['DejaVu Sans', 'Liberation Sans'],
    'axes.spines.top': False,
    'axes.spines.right': False,
    'pdf.fonttype': 42,
    'font.size': 11,
    'axes.labelsize': 12,
    'axes.titlesize': 13,
})

GROUPS = [f'Group {i}' for i in range(1, 6)]
THRESHOLD = 0.80
EDGES = np.round(np.linspace(0.8, 1.0, 11), 10)  # 0.02 => 10 bars


def get_data(path):
    df = pd.read_csv(path, encoding='utf-8-sig')
    required = {'group', 'similarity_to_C32_1_minus_D'}
    if not required.issubset(df.columns):
        raise ValueError(f'Missing columns: {required - set(df.columns)}; got {list(df.columns)}')
    df['group'] = df['group'].astype(str).str.strip()
    df['S'] = pd.to_numeric(df['similarity_to_C32_1_minus_D'], errors='coerce')
    df = df[df.group.isin(GROUPS) & df.S.between(0, 1)].copy()
    missing = [x for x in GROUPS if x not in set(df.group)]
    if missing: raise ValueError(f'Missing groups: {missing}')
    return df


def save(fig, root):
    fig.savefig(str(root)+'.png', dpi=300, bbox_inches='tight', facecolor='white')
    fig.savefig(str(root)+'.pdf', bbox_inches='tight', facecolor='white')
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('csv', help='01_all_structures_to_C32_oganov.csv')
    ap.add_argument('--outdir', default='C32_oganov_new_figures')
    args=ap.parse_args()
    output=Path(args.outdir); output.mkdir(parents=True,exist_ok=True)
    df=get_data(args.csv)
    stats=[]
    bars=[]

    for index, group in enumerate(GROUPS, 1):
        sub=df[df.group==group]
        s=sub.S.to_numpy(dtype=float)
        hist,_=np.histogram(s,bins=EDGES)
        pct=hist/len(s)*100
        midpoint=(EDGES[:-1]+EDGES[1:])/2
        high=(s>=THRESHOLD).sum()
        stats.append(dict(group=group,n=len(s),n_ge_080=int(high),fraction_ge_080_pct=high/len(s)*100,
                          fraction_ge_090_pct=(s>=0.90).mean()*100,
                          fraction_ge_095_pct=(s>=0.95).mean()*100,
                          mean_similarity=float(np.mean(s)),sd_similarity=float(np.std(s,ddof=1))))
        for lo,hi,v,k in zip(EDGES[:-1],EDGES[1:],pct,hist):
            bars.append(dict(group=group,bin_left=lo,bin_right=hi,n_in_bin=k,percent_of_all_group_structures=v))
        fig,ax=plt.subplots(figsize=(8.6,5.0))
        ax.bar(midpoint,pct,width=0.017,color='#4474B8',edgecolor='white',linewidth=.65)
        ax.set(xlim=(0.795,1.005),xlabel='Oganov fingerprint similarity to C32-C2/m (S = 1 - D)',
               ylabel='Fraction of all structures in group (%)')
        ax.set_xticks(EDGES)
        ax.set_xticklabels([f'{x:.2f}' for x in EDGES],rotation=45)
        ax.set_title(f'{group}  |  n = {len(s)}  |  S >= 0.80: {high/len(s)*100:.1f}%')
        ax.grid(axis='y',alpha=.2); ax.set_axisbelow(True)
        save(fig,output/f'Fig_{index}_{group.replace(" ", "_")}_bars_002')

    st=pd.DataFrame(stats)
    pd.DataFrame(bars).to_csv(output/'bar_bin_values.csv',index=False)
    st.to_csv(output/'five_group_threshold_summary.csv',index=False)

    # Fig 6: five points, each percentage of S >= 0.8 with grand mean line
    fig,ax=plt.subplots(figsize=(8.6,5))
    x=np.arange(1,6)
    y=st.fraction_ge_080_pct.to_numpy()
    ax.scatter(x,y,s=125,color='#4474B8',zorder=3)
    for xi,yi in zip(x,y): ax.annotate(f'{yi:.1f}%',(xi,yi),xytext=(0,12),textcoords='offset points',ha='center',fontsize=10)
    mean=y.mean(); ax.axhline(mean,color='#D28443',linestyle='--',linewidth=1.7,
                               label=f'Five-group mean = {mean:.2f}%')
    ax.set(xlim=(.5,5.5),xticks=x,xticklabels=GROUPS,
           ylabel='Structures with similarity S >= 0.80 (%)',
           title='Between-group reproducibility of C32-like structural fraction')
    ax.set_ylim(max(0,y.min()-max(5,(y.max()-y.min())*2)),min(100,y.max()+max(7,(y.max()-y.min())*2)))
    ax.grid(axis='y',alpha=.2); ax.legend(loc='best'); ax.set_axisbelow(True)
    save(fig,output/'Fig_6_five_group_fraction_scatter')

    # Fig 7: EVERY structure as jittered scatter, five vertical strips
    fig,ax=plt.subplots(figsize=(10,6))
    rng=np.random.default_rng(2026)  # deterministic x jitter; y values unchanged
    for i,group in enumerate(GROUPS,1):
        s=df.loc[df.group==group,'S'].to_numpy(dtype=float)
        j=rng.uniform(-.27,.27,size=len(s))
        ax.scatter(np.full(len(s),i)+j,s,s=8,color='#4474B8',alpha=.19,rasterized=True,linewidths=0)
        ax.scatter([i],[s.mean()],marker='D',s=78,color='#D28443',edgecolors='white',zorder=5)
    ax.axhline(.80,color='#B94D51',linestyle='--',linewidth=1.3,label='Similarity threshold S = 0.80')
    ax.set(xlim=(.45,5.55),xticks=np.arange(1,6),xticklabels=GROUPS,ylim=(0,1.01),
           ylabel='Oganov fingerprint similarity to C32-C2/m (S = 1 - D)',
           title='Individual generated structures relative to C32-C2/m')
    ax.scatter([],[],marker='D',s=60,color='#D28443',label='Group mean')
    ax.legend(loc='lower left'); ax.grid(axis='y',alpha=.15); ax.set_axisbelow(True)
    save(fig,output/'Fig_7_all_structures_similarity_scatter')

    print(st.to_string(index=False, float_format=lambda a:f'{a:.4f}'))
    print(f'Created 7 figures (PNG and PDF) and 2 numeric CSV files: {output.resolve()}')

if __name__=='__main__': main()
